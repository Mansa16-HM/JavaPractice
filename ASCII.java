public class ASCII
    {
        public static void main(String args[])
            {
                for(char c='A' ; c <= 'Z' ;c++)
                    {
                        System.out.print(c);
                    }
                    System.out.println();
                for(char c='z'; c >= 'a'; c--  )
                {
                    System.out.print(c);
                }
                 System.out.println();
                for(char c='A' ; c <= 'z' ;c++)
                    {
                        System.out.print(c);
                    }
                    System.out.println();
                    
            }
    }