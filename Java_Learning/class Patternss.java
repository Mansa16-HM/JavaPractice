class Patternss
{
    public static void main(String args[])
    {
        for(int i=1;i<=5;i++)
            {
                for(int j=1;j<=5;i++)
                    {
                        if(i>=j){
                            System.out.println("*");
                        }
                        System.out.println();
                    }
            }
    }
}