public class Demo256{
    public static void main(String []args)
    {
        //integer data types
        byte ByteValue=10;//1 byte n range ----128 to 127
        short shortValue=120;//2 bytes n range --
        int integerValue=12;//4 bytes
        long longValue=1000L;//8 bytes

        //float 
        float floatValue=12.78f;
        double doubleValue=68.87568d;//in java all the decimal values are double as default 

        char CharValue='A';
        boolean BooleanValue=true;

        String stringValues="Hello World";

        System.out.println("Byte Value     :"+ByteValue);
        System.out.println("Short Value   :"+shortValue);
        System.out.println("Integer Value :"+integerValue);
        System.out.println("Long Value    :"+longValue);

        System.out.println(" Floating Value:"+floatValue);
        System.out.println("double Value:"+doubleValue);
        System.out.println("Character Value:"+CharValue);
        System.out.println("Boolean Value:"+BooleanValue);

        System.out.println("String Value:"+stringValues);



    }
}